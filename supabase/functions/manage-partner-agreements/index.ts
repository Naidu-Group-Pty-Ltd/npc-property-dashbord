/**
 * manage-partner-agreements — the Agreement Centre's Command Centre engine.
 *
 * The original register actions (list/get/create/update/transition/new_version/
 * delete_draft/effective_schedule) are unchanged in behaviour. On top of them
 * sits the digital lifecycle:
 *
 *   record_review        internal review decision (approve for issue / return)
 *   issue_to_partner     freeze a version row + put it in the partner's portal
 *   withdraw             pull an issued agreement back before execution
 *   counter_sign         the issuer's signature; finalises execution
 *   resolve_change_request  answer a partner's structured request
 *   set_owner            reassign the responsible Command Centre user
 *   duplicate_check      active/in-flight agreements for a partner (warn, not block)
 *   issuer_defaults      tenant identity for wizard prefill
 *   validate_issue       the pre-issue validation panel, server-computed
 *
 * …and disposition — the three ways an agreement leaves the working list:
 *
 *   void_agreement       declare it of no effect (reasoned, permanent, cascades)
 *   archive / restore    file it away and bring it back (reversible, no effect
 *                        on status, commission or the partner's copy)
 *   delete_agreement     destroy a row that never left the building
 *
 * Every one of those re-derives its own eligibility from the database rather
 * than trusting what the browser thought was possible, using the same pure
 * rules the UI greys the buttons out with (`lifecycle.pure.ts`).
 *
 * Authorisation: staff session + the `agreements` module, deny-by-default —
 * reads need can_view, mutations can_edit (`_shared/authz.ts`, not the
 * allow-by-default `_shared/permissions.ts`). The transition map is the shared
 * `AGREEMENT_TRANSITIONS`, so the server and both UIs agree on what is legal.
 *
 * Versioning rule: nothing externally visible is ever silently overwritten.
 * `issue_to_partner` freezes field values + brand snapshot + template content
 * hash onto a `partner_agreement_versions` row; a reissue supersedes the prior
 * row and records a field-level diff. The executed master is generated by
 * `counter_sign` and stored write-once in the `partner-agreements` bucket —
 * automatic return to the Command Centre, no manual re-upload.
 */
